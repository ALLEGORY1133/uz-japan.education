const dicts: Record<Locale, Dict> = { uz, en, ja };

/** t("nav.news") — tanlangan tildagi matn; topilmasa UZ, so'ng kalitning o'zi. */
export function getT(locale: Locale) {
  const d = dicts[locale] || uz;
  return (key: string) => d[key] ?? uz[key] ?? key;
}

export type TFn = ReturnType<typeof getT>;

/** Berilgan prefiks bilan boshlanuvchi barcha tarjimalar (prefikssiz kalit bilan). */
export function pickPrefix(locale: Locale, prefix: string): Record<string, string> {
  const d = dicts[locale] || uz;
  const out: Record<string, string> = {};
  for (const k of Object.keys(uz)) if (k.startsWith(prefix)) out[k.slice(prefix.length)] = d[k] ?? uz[k];
  return out;
}

const intlLocale: Record<Locale, string> = { uz: "uz-UZ", ja: "ja-JP", en: "en-GB" };

export function formatDate(value: string | null | undefined, locale: Locale): string {
  if (!value) return "";
  const d = new Date(value);
  if (Number.isNaN(d.getTime())) return value;
  return new Intl.DateTimeFormat(intlLocale[locale], {
    day: "numeric",
    month: "long",
    year: "numeric",
    timeZone: "Asia/Tashkent",
  }).format(d);
}

/** Kartadagi qisqa sana: kun raqami va oy nomi (Toshkent vaqti). */
export function formatDayMonth(value: string | null | undefined, locale: Locale): { d: string; m: string } {
  const d = value ? new Date(value) : null;
  if (!d || Number.isNaN(d.getTime())) return { d: "", m: "" };
  const opt = { timeZone: "Asia/Tashkent" } as const;
  return {
    d: new Intl.DateTimeFormat(intlLocale[locale], { day: "numeric", ...opt }).format(d),
    m: new Intl.DateTimeFormat(intlLocale[locale], { month: "short", ...opt }).format(d),
  };
}

